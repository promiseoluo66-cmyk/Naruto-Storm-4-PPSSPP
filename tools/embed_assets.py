#!/usr/bin/env python3
"""
Embed binary files into a C source file so they live inside the EBOOT.

Usage:  python3 tools/embed_assets.py out.c name=path [name=path ...]
Produces for each:  const unsigned char name[]; const unsigned int name_size;
"""
import sys


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    out = ["/* GENERATED by tools/embed_assets.py - do not edit or commit. */"]
    for spec in sys.argv[2:]:
        name, path = spec.split("=", 1)
        data = open(path, "rb").read()
        out.append("const unsigned int %s_size = %d;" % (name, len(data)))
        out.append("const unsigned char %s[] __attribute__((aligned(16))) = {" % name)
        for i in range(0, len(data), 24):
            out.append(",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
    open(sys.argv[1], "w").write("\n".join(out) + "\n")
    print("wrote", sys.argv[1])


if __name__ == "__main__":
    main()
