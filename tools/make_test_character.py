#!/usr/bin/env python3
"""
Generate an ORIGINAL low-poly test character (no third-party assets).

Outputs into OUT_DIR:
  test_character.obj   Wavefront OBJ with per-vertex colours ("v x y z r g b")
  test_texture.nmtx    64x64 greyscale cloth-weave texture (NMTX v1, RGB565)

The OBJ is plain interchange data: you can replace it with a model exported
from Blender (File > Export > Wavefront OBJ, with vertex colours) and run
tools/obj2nmdl.py on it instead.

Coordinates: metres, +Y up, character faces +Z, feet at Y=0.
"""
import struct
import sys
import os

parts = []  # each part = (list of quads, colour)


def box(cx, cy, cz, w, h, d, col):
    x0, x1 = cx - w / 2, cx + w / 2
    y0, y1 = cy - h / 2, cy + h / 2
    z0, z1 = cz - d / 2, cz + d / 2
    # quads, counter-clockwise when seen from outside
    quads = [
        [(x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)],  # front +z
        [(x1, y0, z0), (x0, y0, z0), (x0, y1, z0), (x1, y1, z0)],  # back -z
        [(x0, y0, z0), (x0, y0, z1), (x0, y1, z1), (x0, y1, z0)],  # left -x
        [(x1, y0, z1), (x1, y0, z0), (x1, y1, z0), (x1, y1, z1)],  # right +x
        [(x0, y1, z1), (x1, y1, z1), (x1, y1, z0), (x0, y1, z0)],  # top
        [(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)],  # bottom
    ]
    parts.append((quads, col))


def spike(cx, cy, cz, base, height, col, lean_x=0.0, lean_z=0.0):
    """Four-sided pyramid (hair spike)."""
    b = base / 2
    a = [(cx - b, cy, cz - b), (cx + b, cy, cz - b), (cx + b, cy, cz + b), (cx - b, cy, cz + b)]
    tip = (cx + lean_x, cy + height, cz + lean_z)
    quads = []
    for i in range(4):
        p, q = a[i], a[(i + 1) % 4]
        quads.append([p, q, tip, tip])  # degenerate quad = triangle
    parts.append((quads, col))


SKIN = (0.95, 0.80, 0.65)
HAIR = (0.10, 0.10, 0.16)
SHIRT = (0.20, 0.35, 0.70)
PANTS = (0.18, 0.20, 0.28)
BAND = (0.75, 0.78, 0.85)
SCARF = (0.85, 0.30, 0.20)
SHOE = (0.12, 0.12, 0.14)

# legs + shoes
box(-0.18, 0.42, 0.0, 0.26, 0.84, 0.28, PANTS)
box(0.18, 0.42, 0.0, 0.26, 0.84, 0.28, PANTS)
box(-0.18, 0.06, 0.05, 0.28, 0.12, 0.40, SHOE)
box(0.18, 0.06, 0.05, 0.28, 0.12, 0.40, SHOE)
# torso + belt
box(0.0, 1.25, 0.0, 0.70, 0.80, 0.38, SHIRT)
box(0.0, 0.88, 0.0, 0.72, 0.12, 0.40, (0.25, 0.20, 0.15))
# arms + hands
box(-0.46, 1.30, 0.0, 0.20, 0.70, 0.24, SHIRT)
box(0.46, 1.30, 0.0, 0.20, 0.70, 0.24, SHIRT)
box(-0.46, 0.88, 0.0, 0.18, 0.18, 0.20, SKIN)
box(0.46, 0.88, 0.0, 0.18, 0.18, 0.20, SKIN)
# scarf
box(0.0, 1.70, 0.0, 0.50, 0.14, 0.40, SCARF)
box(0.0, 1.45, -0.24, 0.22, 0.60, 0.08, SCARF)
# head, headband, hair
box(0.0, 1.95, 0.0, 0.50, 0.50, 0.46, SKIN)
box(0.0, 2.10, 0.0, 0.54, 0.10, 0.50, (0.15, 0.20, 0.55))
box(0.0, 2.10, 0.26, 0.24, 0.09, 0.03, BAND)
box(0.0, 2.24, -0.02, 0.54, 0.14, 0.50, HAIR)
spike(-0.17, 2.31, 0.0, 0.16, 0.30, HAIR, lean_x=-0.06)
spike(0.0, 2.31, 0.0, 0.18, 0.36, HAIR)
spike(0.17, 2.31, 0.0, 0.16, 0.30, HAIR, lean_x=0.06)
spike(0.0, 2.20, -0.28, 0.20, 0.26, HAIR, lean_z=-0.18)
# eyes
box(-0.11, 1.97, 0.235, 0.09, 0.07, 0.02, (0.05, 0.05, 0.08))
box(0.11, 1.97, 0.235, 0.09, 0.07, 0.02, (0.05, 0.05, 0.08))


def write_obj(path):
    lines = ["# Original low-poly test character (generated by tools/make_test_character.py)",
             "# No third-party assets. Units: metres, +Y up, faces +Z.",
             "o test_character",
             "vt 0 0", "vt 1 0", "vt 1 1", "vt 0 1"]
    vi = 1
    face_lines = []
    for quads, col in parts:
        for quad in quads:
            idx = []
            for (x, y, z) in quad:
                lines.append("v %.4f %.4f %.4f %.3f %.3f %.3f" % (x, y, z, col[0], col[1], col[2]))
                idx.append(vi)
                vi += 1
            if quad[2] == quad[3]:  # triangle
                face_lines.append("f %d/1 %d/2 %d/3" % (idx[0], idx[1], idx[2]))
            else:
                face_lines.append("f %d/1 %d/2 %d/3 %d/4" % tuple(idx))
    with open(path, "w") as f:
        f.write("\n".join(lines + face_lines) + "\n")


def write_texture(path, size=64):
    """Greyscale cloth weave. R=G=B so the 5650 channel order cannot matter."""
    out = bytearray(b"NMTX")
    out += struct.pack("<IIII", 1, size, size, 1)  # version, w, h, RGB565
    for y in range(size):
        for x in range(size):
            weave = 0.86 + 0.10 * (((x // 2) + (y // 2)) % 2) + 0.04 * ((x + y) % 4 == 0)
            v = max(0.0, min(1.0, weave))
            r5 = int(v * 31 + 0.5)
            g6 = min(63, r5 * 2 + (1 if r5 > 15 else 0))
            px = r5 | (g6 << 5) | (r5 << 11)
            out += struct.pack("<H", px)
    with open(path, "wb") as f:
        f.write(out)


if __name__ == "__main__":
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "assets/chr/test"
    os.makedirs(out_dir, exist_ok=True)
    write_obj(os.path.join(out_dir, "test_character.obj"))
    write_texture(os.path.join(out_dir, "test_texture.nmtx"))
    print("wrote", out_dir)
